// Release signing lives outside the repo (~/.config/gravity-well-signing/);
// the release build type falls back to the debug key when absent.
val signingProps: Properties? = run {
    val f = File(System.getProperty("user.home"), ".config/gravity-well-signing/key.properties")
    if (f.isFile) Properties().apply { f.inputStream().use { load(it) } } else null
}

